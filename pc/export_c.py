"""Write the trained models into board/model.h as plain C arrays and ifs."""
from datetime import datetime
from config import BOARD, CLASSES, FEATURES, BASE


def num(v):
    t = f"{float(v):.7g}"
    if "." not in t and "e" not in t and "inf" not in t and "nan" not in t:
        t += ".0"
    return t + "f"


def arr(vals):
    return ", ".join(num(v) for v in vals)


def tree_code(tree):
    t = tree.tree_
    lines = []

    def walk(node, depth):
        pad = "    " * depth
        if t.children_left[node] == -1:
            lines.append(f"{pad}return {int(t.value[node][0].argmax())};")
            return
        f, thr = t.feature[node], t.threshold[node]
        lines.append(f"{pad}if (f[{f}] <= {num(thr)}) {{   /* {FEATURES[f]} */")
        walk(t.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        walk(t.children_right[node], depth + 1)
        lines.append(f"{pad}}}")

    walk(0, 1)
    return "\n".join(lines)


def write_model_h(scaler, tree, mlp, knn_damage, Xs, y, h_mean, h_std,
                  change_thr, novelty_thr, unsafe, dataset):
    W1, W2 = mlp.coefs_
    b1, b2 = mlp.intercepts_
    H = W1.shape[1]
    nf, nc = len(FEATURES), len(CLASSES)
    s = []
    s.append(f"/* AUTO-GENERATED by pc/train.py from '{dataset}' data on "
             f"{datetime.now():%Y-%m-%d %H:%M}. Do not edit by hand: retrain instead. */")
    s.append("#ifndef MODEL_H\n#define MODEL_H\n")
    s.append(f"#define N_FEAT {nf}\n#define N_CLASS {nc}\n#define N_HIDDEN {H}")
    s.append(f"#define KNN_N {len(y)}\n")
    s.append("/* calibration baseline the model was trained against (see features.normalize) */")
    s.append(f"static const float BASE_INIT[5] = {{{', '.join(f'{v}f' for v in BASE)}}};\n")
    s.append("static const char *const CLASS_NAME[N_CLASS] = {"
             + ", ".join(f'"{c.upper()}"' for c in CLASSES) + "};")
    s.append(f"/* feature order: {', '.join(FEATURES)} */\n")
    s.append(f"static const float SC_MEAN[N_FEAT] = {{{arr(scaler.mean_)}}};")
    s.append(f"static const float SC_STD[N_FEAT]  = {{{arr(scaler.scale_)}}};\n")
    s.append("/* Decision tree (works on raw, unscaled features) */")
    s.append("static int tree_predict(const float *f)\n{\n" + tree_code(tree) + "\n}\n")
    s.append("/* Neural network: hidden = relu(W1 * x + b1), out = W2 * hidden + b2 */")
    s.append(f"static const float NN_W1[N_HIDDEN][N_FEAT] = {{\n"
             + ",\n".join(f"    {{{arr(W1[:, j])}}}" for j in range(H)) + "\n};")
    s.append(f"static const float NN_B1[N_HIDDEN] = {{{arr(b1)}}};")
    s.append(f"static const float NN_W2[N_CLASS][N_HIDDEN] = {{\n"
             + ",\n".join(f"    {{{arr(W2[:, k])}}}" for k in range(nc)) + "\n};")
    s.append(f"static const float NN_B2[N_CLASS] = {{{arr(b2)}}};\n")
    s.append("/* Health score: health = 100 * (1 - mean KNN_DAMAGE of the 3 nearest labelled flicks) */")
    s.append(f"#define UNSAFE_HEALTH {num(unsafe)}\n")
    s.append("/* Change detector: healthy baseline (raw features) */")
    s.append(f"static const float HB_MEAN[N_FEAT] = {{{arr(h_mean)}}};")
    s.append(f"static const float HB_STD[N_FEAT]  = {{{arr(h_std)}}};")
    s.append(f"#define CHANGE_THR {num(change_thr)}\n")
    s.append("/* kNN memory (scaled features). Teach mode adds more in RAM. */")
    s.append(f"#define NOVELTY_THR {num(novelty_thr)}")
    s.append("static const float KNN_X[KNN_N][N_FEAT] = {\n"
             + ",\n".join(f"    {{{arr(r)}}}" for r in Xs) + "\n};")
    s.append("static const unsigned char KNN_Y[KNN_N] = {" + ", ".join(str(int(v)) for v in y) + "};")
    s.append("static const float KNN_DAMAGE[KNN_N] = {" + arr(knn_damage) + "};  /* -1 = unlabelled */\n")
    s.append("#endif")
    BOARD.mkdir(exist_ok=True)
    (BOARD / "model.h").write_text("\n".join(s) + "\n", encoding="utf-8")
    print(f"wrote {BOARD / 'model.h'}")
